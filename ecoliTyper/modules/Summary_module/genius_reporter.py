# MASTER REPORTER CLASS 
# =============================================================================
class GeniusUltimateReporter:
    """
    Orchestrates the entire analysis pipeline:
    1. Find all HTML report files in the input directory.
    2. Parse each report and integrate data.
    3. Classify pathotypes.
    4. Generate JSON, CSV, and HTML outputs.
    """
    
    def __init__(self, input_dir: Path):
        self.input_dir = Path(input_dir)
        self.output_dir = self.input_dir / "GENIUS_ECOLI_ULTIMATE_REPORTS"
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.parser = UltimateHTMLParser()
        self.analyzer = UltimateDataAnalyzer()
        self.html_generator = UltimateHTMLGenerator(self.analyzer)
        self.metadata = {
            "tool_name": "GENIUS E.coli Ultimate Reporter (Enhanced)",
            "version": "4.1.0",
            "author": "Brown Beckley <brownbeckley94@gmail.com>",
            "affiliation": "University of Ghana Medical School",
            "analysis_date": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "input_directory": str(self.input_dir)
        }
    
    def find_html_files(self) -> Dict[str, List[Path]]:
        """
        Recursively search for HTML report files and classify by type.
        Returns a dictionary with keys: mlst, serotype, chtyper, phylogrouping, amrfinder, abricate, qc.
        """
        print("🔍 Searching for HTML reports...")
        html_files = {
            'mlst': [], 'serotype': [], 'chtyper': [], 'phylogrouping': [],
            'amrfinder': [], 'abricate': [], 'qc': []
        }
        for html_file in self.input_dir.glob("**/*.html"):
            name = html_file.name.lower()
            if 'mlst' in name:
                html_files['mlst'].append(html_file)
            elif 'serotype' in name:
                html_files['serotype'].append(html_file)
            elif 'chtyper' in name or 'fumc' in name:
                html_files['chtyper'].append(html_file)
            elif 'phylogroup' in name or 'clermont' in name:
                html_files['phylogrouping'].append(html_file)
            elif 'amr' in name or 'resistance' in name:
                html_files['amrfinder'].append(html_file)
            elif 'fasta_qc' in name or 'qc_summary' in name:
                html_files['qc'].append(html_file)
            elif 'abricate' in name or any(db in name for db in self.parser.abricate_databases):
                html_files['abricate'].append(html_file)
        # Report found files
        for k, v in html_files.items():
            if v:
                print(f"  📁 {k.upper()}: {len(v)} files found")
        return html_files
    
    def integrate_all_data(self, html_files: Dict[str, List[Path]]) -> Dict[str, Any]:
        """
        Parse all HTML reports and merge data into a single integrated dictionary.
        Also classifies pathotypes for each sample.
        """
        print("\n🔗 Integrating data...")
        integrated = {
            'metadata': self.metadata,
            'samples': {},
            'patterns': {},
            'gene_centric': {},
            'qc_data': {},
            'mutation_data': {}
        }
        
        # Parse QC report if available
        if html_files['qc']:
            integrated['qc_data'] = self.parser.parse_qc_report(html_files['qc'][0])
        
        # Parse MLST
        mlst_data = {}
        if html_files['mlst']:
            mlst_data = self.parser.parse_mlst_report(html_files['mlst'][0])
        
        # Parse Serotype
        serotype_data = {}
        if html_files['serotype']:
            serotype_data = self.parser.parse_serotype_report(html_files['serotype'][0])
        
        # Parse CHTyper
        chtyper_data = {}
        if html_files['chtyper']:
            chtyper_data = self.parser.parse_chtyper_report(html_files['chtyper'][0])
        
        # Parse Phylogrouping
        phylogrouping_data = {}
        if html_files['phylogrouping']:
            phylogrouping_data = self.parser.parse_phylogrouping_report(html_files['phylogrouping'][0])
        
        # Parse AMRfinder
        amr_by_sample, amr_gene_freq = {}, {}
        if html_files['amrfinder']:
            amr_by_sample, amr_gene_freq = self.parser.parse_amrfinder_report(html_files['amrfinder'][0])
        
        # Parse ABRicate databases
        abricate_by_sample = defaultdict(dict)
        abricate_gene_freq = {}
        for f in html_files['abricate']:
            genes_by_sample, gene_freq = self.parser.parse_abricate_database_report(f)
            # Determine database name from filename (simplified)
            db_name = 'unknown'
            for db in self.parser.abricate_databases:
                if db in f.name.lower():
                    db_name = db
                    break
            for samp, gs in genes_by_sample.items():
                abricate_by_sample[samp][db_name] = gs
            abricate_gene_freq[db_name] = gene_freq
        
        # Parse mutation summary HTML
        mutation_html = self.input_dir / "mutation_summary.html"
        if not mutation_html.exists():
            mutation_html = self.input_dir / "staph_amrfinder_results" / "mutation_summary.html"
        if mutation_html.exists():
            integrated['mutation_data'] = self.parser.parse_mutation_summary_html(mutation_html)
        else:
            print("  ⚠️ mutation_summary.html not found; mutation tab will be empty")
        
        # Collect all unique sample IDs
        all_samples = set()
        all_samples.update(mlst_data.keys())
        all_samples.update(serotype_data.keys())
        all_samples.update(chtyper_data.keys())
        all_samples.update(phylogrouping_data.keys())
        all_samples.update(amr_by_sample.keys())
        all_samples.update(abricate_by_sample.keys())
        all_samples.update(integrated['qc_data'].keys())
        
        if not all_samples:
            print("❌ No samples found in any report!")
            return {}
        
        print(f"📊 Found {len(all_samples)} unique samples")
        
        # Integrate data for each sample and classify pathotype
        for sample in all_samples:
            # Collect virulence genes from VFDB and ecoli_vf databases
            virulence_genes = []
            for db in ['vfdb', 'ecoli_vf']:
                if db in abricate_by_sample.get(sample, {}):
                    virulence_genes.extend(abricate_by_sample[sample][db])
            # Classify pathotype
            pathotype = self.analyzer.classify_pathotype(virulence_genes)
            
            integrated['samples'][sample] = {
                'mlst': mlst_data.get(sample, {'ST': 'ND', 'Allele_Profile': 'ND'}),
                'serotype': serotype_data.get(sample, {'Serotype': 'ND', 'O_Type': 'ND', 'H_Type': 'ND'}),
                'chtyper': chtyper_data.get(sample, {'FumC_Type': 'ND', 'FimH_Type': 'ND', 'CH_Type': 'ND'}),
                'phylogrouping': phylogrouping_data.get(sample, {'Clermont_Type': 'ND'}),
                'amr_genes': amr_by_sample.get(sample, []),
                'virulence_genes': list(set(virulence_genes)),
                'pathotype': pathotype
            }
        
        # Store gene frequencies for gene-centric tables
        integrated['gene_frequencies'] = {
            'amrfinder': amr_gene_freq,
            'abricate': abricate_gene_freq
        }
        
        # Generate gene-centric tables and cross-genome patterns
        print("\n🧠 Processing gene-centric analysis...")
        total_samples = len(all_samples)
        integrated['gene_centric'] = self.analyzer.create_gene_centric_tables(integrated, total_samples)
        integrated['patterns'] = self.analyzer.create_cross_genome_patterns(integrated)
        
        return integrated
    
    def generate_json_report(self, data: Dict[str, Any]) -> Path:
        """Save all integrated data as a JSON file."""
        print("\n📝 Generating JSON report...")
        out = self.output_dir / "genius_ecoli_ultimate_report.json"
        # Use default=str to handle non-serializable objects
        with open(out, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=2, default=str)
        print(f"    ✅ JSON saved: {out}")
        return out
    
    def generate_csv_reports(self, data: Dict[str, Any]):
        """Generate CSV files for sample overview, AMR genes, virulence genes, plasmids, bacmet, and pathotype."""
        print("\n📊 Generating CSV reports...")
        
        # Sample overview CSV
        samples_df = pd.DataFrame([{
            'Sample': s,
            'ST': d['mlst']['ST'],
            'Serotype': d['serotype']['Serotype'],
            'Phylogroup': d['phylogrouping']['Clermont_Type'],
            'CH_Type': d['chtyper']['CH_Type'],
            'Pathotype': d['pathotype'],
            'AMR_Count': len(d['amr_genes']),
            'Virulence_Count': len(d['virulence_genes'])
        } for s, d in data['samples'].items()])
        samples_df.to_csv(self.output_dir / "sample_overview.csv", index=False)
        
        # AMR genes CSV (gene-centric)
        amr_rows = []
        for db, genes in data['gene_centric'].get('amr_databases', {}).items():
            for g in genes:
                amr_rows.append({
                    'Gene': g['gene'],
                    'Database': g['database'],
                    'Count': g['count'],
                    'Percentage': g.get('percentage', 0),
                    'Genomes': ';'.join(g['genomes'])
                })
        if amr_rows:
            pd.DataFrame(amr_rows).to_csv(self.output_dir / "amr_genes.csv", index=False)
        
        # Virulence genes CSV
        vir_rows = []
        for db, genes in data['gene_centric'].get('virulence_databases', {}).items():
            for g in genes:
                vir_rows.append({
                    'Gene': g['gene'],
                    'Database': g['database'],
                    'Count': g['count'],
                    'Percentage': g.get('percentage', 0),
                    'Genomes': ';'.join(g['genomes'])
                })
        if vir_rows:
            pd.DataFrame(vir_rows).to_csv(self.output_dir / "virulence_genes.csv", index=False)
        
        # Plasmid markers CSV
        plasmid_rows = []
        for db, genes in data['gene_centric'].get('plasmid_databases', {}).items():
            for g in genes:
                plasmid_rows.append({
                    'Marker': g['gene'],
                    'Database': g['database'],
                    'Count': g['count'],
                    'Percentage': g.get('percentage', 0),
                    'Genomes': ';'.join(g['genomes'])
                })
        if plasmid_rows:
            pd.DataFrame(plasmid_rows).to_csv(self.output_dir / "plasmid_markers.csv", index=False)
        
        # Bacmet genes CSV
        bacmet_rows = []
        for db, genes in data['gene_centric'].get('bacmet_databases', {}).items():
            for g in genes:
                bacmet_rows.append({
                    'Gene': g['gene'],
                    'Database': g['database'],
                    'Count': g['count'],
                    'Percentage': g.get('percentage', 0),
                    'Genomes': ';'.join(g['genomes'])
                })
        if bacmet_rows:
            pd.DataFrame(bacmet_rows).to_csv(self.output_dir / "bacmet_genes.csv", index=False)
        
        # Mutations CSV
        mutations = data.get('mutation_data', {}).get('mutations', [])
        if mutations:
            mut_rows = []
            for m in mutations:
                mut_rows.append({
                    'Gene': m['gene'],
                    'Mutation': m['mutation'],
                    'Class': m['class'],
                    'Subclass': m['subclass'],
                    'Count': m['count'],
                    'Genomes': ';'.join(m['genomes'])
                })
            pd.DataFrame(mut_rows).to_csv(self.output_dir / "mutations.csv", index=False)
        
        # High-risk combinations CSV
        high = data['patterns'].get('high_risk_combinations', [])
        if high:
            pd.DataFrame(high).to_csv(self.output_dir / "high_risk_combinations.csv", index=False)
        
        print("    ✅ CSV reports generated.")
    
    def run(self):
        """Execute the complete analysis pipeline."""
        print("=" * 80)
