            for _, row in df.iterrows():
                sample = row['normalized_sample']
                serotype = str(row.get('Serotype', 'ND')) if 'Serotype' in df.columns else 'ND'
                o_type = str(row.get('O-type', 'ND')) if 'O-type' in df.columns else str(row.get('O_Type', 'ND'))
                h_type = str(row.get('H-type', 'ND')) if 'H-type' in df.columns else str(row.get('H_Type', 'ND'))
                results[sample] = {'Serotype': serotype, 'O_Type': o_type, 'H_Type': h_type}
