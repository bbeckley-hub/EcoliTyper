    def parse_amrfinder_report(self, file_path: Path, total_samples: int = 0) -> Tuple[Dict[str, List], Dict[str, Dict]]:
        """Parse AMRfinder HTML report."""
        print(f"  🧬 Parsing AMRfinder: {file_path.name}")
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                html_content = f.read()
            soup = BeautifulSoup(html_content, 'html.parser')
            tables = soup.find_all('table')
            if len(tables) < 2:
                return {}, {}
            gene_frequencies = {}
            df2 = self.parse_html_table(str(tables[1]), 0)
            if not df2.empty and 'Gene' in df2.columns:
                for _, row in df2.iterrows():
                    gene = str(row['Gene']).strip()
                    frequency = str(row.get('Frequency', '0')).strip()
                    genomes = []
                    if 'Genomes' in df2.columns and pd.notna(row.get('Genomes')):
                        genomes_str = str(row['Genomes'])
                        genomes = [self.normalize_sample_id(g.strip()) for g in genomes_str.split(',') if g.strip()]
                    count = 0
                    match = re.search(r'(\d+)', frequency)
                    if match:
                        count = int(match.group(1))
                    percentage = (count / total_samples) * 100 if total_samples > 0 else 0
                    gene_frequencies[gene] = {
                        'count': count,
                        'percentage': round(percentage, 2),
                        'frequency_display': f"{count} ({percentage:.1f}%)",
                        'genomes': genomes,
                        'database': 'amrfinder'
                    }
            genes_by_genome = {}
            df1 = self.parse_html_table(str(tables[0]), 0)
            if not df1.empty and 'Genome' in df1.columns:
                for _, row in df1.iterrows():
                    sample = self.normalize_sample_id(row['Genome'])
                    genes = []
                    if pd.notna(row.get('Genes Detected')):
                        gene_str = str(row['Genes Detected'])
                        genes = [g.strip() for g in gene_str.split(',') if g.strip()]
                    genes_by_genome[sample] = genes
            print(f"    ✓ Found {len(genes_by_genome)} samples, {len(gene_frequencies)} genes")
            return genes_by_genome, gene_frequencies
        except Exception as e:
            print(f"    ❌ Error parsing AMRfinder: {e}")
            return {}, {}
    
    def parse_abricate_database_report(self, file_path: Path, total_samples: int = 0) -> Tuple[Dict[str, List], Dict[str, Dict]]:
        """Parse any ABRicate database HTML report."""
        print(f"  🧬 Parsing ABRicate: {file_path.name}")
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                html_content = f.read()
            soup = BeautifulSoup(html_content, 'html.parser')
            tables = soup.find_all('table')
            if len(tables) < 2:
                return {}, {}
            db_name = 'unknown'
            title_tag = soup.find('title')
            if title_tag:
                title_text = title_tag.get_text()
                match = re.search(r'(\w+)\s+Database', title_text, re.I)
                if match:
                    db_name = match.group(1).lower()
                else:
                    db_name = file_path.stem.lower().replace('ecoli_', '').replace('_summary_report', '')
            gene_frequencies = {}
            df2 = self.parse_html_table(str(tables[1]), 0)
            if not df2.empty and 'Gene' in df2.columns:
                for _, row in df2.iterrows():
                    gene = str(row['Gene']).strip()
                    frequency = str(row.get('Frequency', '0')).strip()
                    genomes = []
                    if 'Genomes' in df2.columns and pd.notna(row.get('Genomes')):
                        genomes_str = str(row['Genomes'])
                        genomes = [self.normalize_sample_id(g.strip()) for g in genomes_str.split(',') if g.strip()]
                    count = 0
                    match = re.search(r'(\d+)', frequency)
                    if match:
                        count = int(match.group(1))
                    percentage = (count / total_samples) * 100 if total_samples > 0 else 0
                    gene_frequencies[gene] = {
                        'count': count,
                        'percentage': round(percentage, 2),
                        'frequency_display': f"{count} ({percentage:.1f}%)",
                        'genomes': genomes,
                        'database': db_name
                    }
            genes_by_genome = {}
            df1 = self.parse_html_table(str(tables[0]), 0)
            if not df1.empty:
                sample_col = None
                for col in df1.columns:
                    if 'genome' in col.lower() or 'sample' in col.lower():
                        sample_col = col
                        break
                if sample_col:
                    for _, row in df1.iterrows():
                        sample = self.normalize_sample_id(row[sample_col])
                        genes = []
                        genes_col = None
                        for col in df1.columns:
                            if 'genes' in col.lower() or 'detected' in col.lower():
                                genes_col = col
                                break
                        if genes_col and pd.notna(row.get(genes_col)):
                            gene_str = str(row[genes_col])
                            genes = [g.strip() for g in gene_str.split(',') if g.strip()]
                        genes_by_genome[sample] = genes
            print(f"    ✓ {db_name.upper()}: {len(genes_by_genome)} samples, {len(gene_frequencies)} genes")
            return genes_by_genome, gene_frequencies
        except Exception as e:
            print(f"    ❌ Error parsing ABRicate report: {e}")
            return {}, {}
    
    def parse_mutation_summary_html(self, file_path: Path) -> Dict[str, Any]:
        """
        Parse mutation_summary.html into a gene‑centric mutation data structure.
        Returns: {'mutations': list of dicts, 'genome_mutation_counts': dict}
        """
        print(f"  🧬 Parsing mutation summary HTML: {file_path.name}")
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                html_content = f.read()
            soup = BeautifulSoup(html_content, 'html.parser')
            mutation_table = None
            for table in soup.find_all('table'):
                if table.find(string=re.compile(r'Gene', re.I)) and table.find(string=re.compile(r'Mutation|Element', re.I)):
                    mutation_table = table
                    break
            if not mutation_table:
                print("    ⚠️ Could not find mutation table in HTML")
                return {}
            # Find header row
            header_row = None
            thead = mutation_table.find('thead')
            if thead:
                header_row = thead.find('tr')
            if not header_row:
                first_row = mutation_table.find('tr')
                if first_row:
                    header_row = first_row
            if not header_row:
                print("    ⚠️ Could not find header row in mutation table")
                return {}
            # Extract headers
            headers = []
            for cell in header_row.find_all(['th', 'td']):
                text = cell.get_text().strip()
                if text:
                    headers.append(text)
            # Map columns
            col_idx = {}
            for idx, h in enumerate(headers):
                h_lower = h.lower()
                if 'gene' in h_lower:
                    col_idx['gene'] = idx
                elif 'mutation' in h_lower or 'element name' in h_lower or 'element_name' in h_lower or 'variant' in h_lower:
                    col_idx['mutation'] = idx
                elif 'class' in h_lower:
                    col_idx['class'] = idx
                elif 'subclass' in h_lower:
                    col_idx['subclass'] = idx
                elif 'genome' in h_lower:
                    col_idx['genomes'] = idx
            # We don't need a count column – we'll count genomes directly
            if 'gene' not in col_idx or 'genomes' not in col_idx:
                print(f"    ⚠️ Missing required columns (gene, genomes). Found: {headers}")
                return {}
            tbody = mutation_table.find('tbody')
            if tbody:
                rows = tbody.find_all('tr')
            else:
                rows = mutation_table.find_all('tr')[1:]  # skip header row
            mutations_list = []
            genome_counts = defaultdict(int)
            for row in rows:
                cells = row.find_all('td')
                if len(cells) <= max(col_idx.values()):
                    continue
                gene = cells[col_idx['gene']].get_text().strip()
                # Mutation name
                mutation = ''
                if 'mutation' in col_idx and col_idx['mutation'] < len(cells):
                    mutation = cells[col_idx['mutation']].get_text().strip()
                # Class and subclass
                class_name = ''
                if 'class' in col_idx and col_idx['class'] < len(cells):
                    class_name = cells[col_idx['class']].get_text().strip()
                subclass = ''
                if 'subclass' in col_idx and col_idx['subclass'] < len(cells):
                    subclass = cells[col_idx['subclass']].get_text().strip()
                # Genomes column – comma separated
                genomes_str = cells[col_idx['genomes']].get_text().strip()
                # Split by comma, clean each genome name
                genomes = [self.normalize_sample_id(g.strip()) for g in genomes_str.split(',') if g.strip()]
                if not genomes:
                    continue
                # Use the actual number of genomes as the count
                count = len(genomes)
                # Update per‑genome mutation counts
                for g in genomes:
                    genome_counts[g] += 1
                mutations_list.append({
                    'gene': gene,
                    'mutation': mutation,
                    'class': class_name,
                    'subclass': subclass,
                    'count': count,
                    'genomes': genomes
                })
            # Sort by count descending
            mutations_list.sort(key=lambda x: x['count'], reverse=True)
            print(f"    ✓ Parsed {len(mutations_list)} unique mutations across {len(genome_counts)} genomes")
            return {
                'mutations': mutations_list,
                'genome_mutation_counts': dict(genome_counts)
            }
        except Exception as e:
            print(f"    ❌ Error parsing mutation summary HTML: {e}")
            import traceback
            traceback.print_exc()
            return {}


