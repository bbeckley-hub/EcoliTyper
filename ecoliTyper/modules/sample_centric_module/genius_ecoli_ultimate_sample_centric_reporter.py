class GeniusUltimateReporter:
    def __init__(self, input_dir: Path):
        self.input_dir = Path(input_dir)
        self.output_dir = self.input_dir / "GENIUS_ECOLI_ULTIMATE_SAMPLE_CENTRIC_REPORTS"
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.parser = UltimateHTMLParser()
        self.analyzer = UltimateDataAnalyzer()
        self.html_generator = UltimateHTMLGenerator(self.analyzer)
        self.metadata = {
            "tool_name": "GENIUS E.coli Ultimate Reporter (Hybrid)",
            "version": "1.0.0",
            "author": "Brown Beckley <brownbeckley94@gmail.com>",
            "affiliation": "University of Ghana Medical School",
            "analysis_date": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "input_directory": str(self.input_dir)
        }

    def find_html_files(self) -> Dict[str, List[Path]]:
        print("🔍 Searching for HTML reports...")
        html_files = {
            'mlst': [], 'serotype': [], 'chtyper': [], 'phylogrouping': [],
            'amrfinder': [], 'abricate': [], 'qc': []
        }
        for html_file in self.input_dir.glob("**/*.html"):
            name = html_file.name.lower()
            if 'mlst' in name:
                html_files['mlst'].append(html_file)
            elif 'serotype' in name:
                html_files['serotype'].append(html_file)
            elif 'chtyper' in name or 'fumc' in name:
                html_files['chtyper'].append(html_file)
            elif 'phylogroup' in name or 'clermont' in name:
                html_files['phylogrouping'].append(html_file)
            elif 'amr' in name or 'resistance' in name:
                html_files['amrfinder'].append(html_file)
            elif 'fasta_qc' in name or 'qc_summary' in name:
                html_files['qc'].append(html_file)
            elif 'abricate' in name or any(db in name for db in self.parser.abricate_databases):
                html_files['abricate'].append(html_file)
        for k, v in html_files.items():
            if v:
                print(f"  📁 {k.upper()}: {len(v)} files found")
        return html_files

    def integrate_all_data(self, html_files: Dict[str, List[Path]]) -> Dict[str, Any]:
        print("\n🔗 Integrating data...")

        integrated = {
            'metadata': self.metadata,
            'samples': {},
            'patterns': {},
            'gene_centric': {},
            'qc_data': {},
            'amrfinder_details': {},
            'abricate_details': {},
            'mutation_details': {}
        }

        # QC from HTML
        if html_files['qc']:
            integrated['qc_data'] = self.parser.parse_qc_report(html_files['qc'][0])

        # Typing from HTML 
        mlst_data = {}
        if html_files['mlst']:
            mlst_data = self.parser.parse_mlst_report(html_files['mlst'][0])

        serotype_data = {}
        if html_files['serotype']:
            serotype_data = self.parser.parse_serotype_report(html_files['serotype'][0])

        chtyper_data = {}
        if html_files['chtyper']:
            chtyper_data = self.parser.parse_chtyper_report(html_files['chtyper'][0])

        phylogrouping_data = {}
        if html_files['phylogrouping']:
            phylogrouping_data = self.parser.parse_phylogrouping_report(html_files['phylogrouping'][0])

        # Merge typing data into a single dictionary
        all_typing_samples = set(mlst_data.keys()) | set(serotype_data.keys()) | set(chtyper_data.keys()) | set(phylogrouping_data.keys())
        typing_data = {}
        for sample in all_typing_samples:
            typing_data[sample] = {
                'ST': mlst_data.get(sample, {}).get('ST', 'ND'),
                'Allele_Profile': mlst_data.get(sample, {}).get('Allele_Profile', 'ND'),
                'Serotype': serotype_data.get(sample, {}).get('Serotype', 'ND'),
                'O_Type': serotype_data.get(sample, {}).get('O_Type', 'ND'),
                'H_Type': serotype_data.get(sample, {}).get('H_Type', 'ND'),
                'FumC_Type': chtyper_data.get(sample, {}).get('FumC_Type', 'ND'),
                'FimH_Type': chtyper_data.get(sample, {}).get('FimH_Type', 'ND'),
                'CH_Type': chtyper_data.get(sample, {}).get('CH_Type', 'ND'),
                'Clermont_Type': phylogrouping_data.get(sample, {}).get('Clermont_Type', 'ND')
            }

        # Sample-centric data from TSV ONLY
        amr_details, amr_gene_counts = self.parser.load_amrfinder_from_tsv(self.input_dir)
        if amr_details:
            print(f"  ✅ Loaded AMRfinder details for {len(amr_details)} samples from TSV")
            integrated['amrfinder_details'] = amr_details
        else:
            print("  ⚠️ AMRfinder TSV not found; AMR tab will be empty.")

        abricate_details, abricate_gene_counts = self.parser.load_abricate_from_tsv(self.input_dir)
        if abricate_details:
            print(f"  ✅ Loaded ABRicate details for {len(abricate_details)} samples from TSV")
            integrated['abricate_details'] = abricate_details
        else:
            print("  ⚠️ ABRicate TSVs not found; virulence/plasmid/bacmet tabs will be empty.")

        mutation_details = self.parser.load_mutations_from_tsv(self.input_dir)
        if mutation_details:
            print(f"  ✅ Loaded mutation details for {len(mutation_details)} samples from TSV")
            integrated['mutation_details'] = mutation_details
        else:
            print("  ⚠️ Mutation TSV not found; mutation tab will be empty.")

        # Build all sample IDs from all sources
        all_sample_ids = set(typing_data.keys())
        all_sample_ids.update(integrated['qc_data'].keys())
        all_sample_ids.update(amr_details.keys())
        all_sample_ids.update(abricate_details.keys())
        all_sample_ids.update(mutation_details.keys())

        if not all_sample_ids:
            print("❌ No samples found!")
            return {}

        print(f"📊 Found {len(all_sample_ids)} unique samples")

        # Build per-sample data
        for sample in all_sample_ids:
            typing = typing_data.get(sample, {})

            amr_genes = []
            virulence_genes = []
            bacmet_genes = []
            plasmid_genes = []

            # From TSV data only
            if sample in amr_details:
                amr_genes.extend([g['gene'] for g in amr_details[sample]])

            if sample in abricate_details:
                for db, genes in abricate_details[sample].items():
                    if db in ['vfdb', 'ecoli_vf']:
                        virulence_genes.extend([g['gene'] for g in genes])
                    elif db == 'bacmet2':
                        bacmet_genes.extend([g['gene'] for g in genes])
                    elif db in ['plasmidfinder', 'ecoh']:
                        plasmid_genes.extend([g['gene'] for g in genes])

            # Deduplicate
            amr_genes = list(set(amr_genes))
            virulence_genes = list(set(virulence_genes))
            bacmet_genes = list(set(bacmet_genes))
            plasmid_genes = list(set(plasmid_genes))

            pathotype = self.analyzer.classify_pathotype(virulence_genes)

            integrated['samples'][sample] = {
                'mlst': {
                    'ST': typing.get('ST', 'ND'),
                    'Allele_Profile': typing.get('Allele_Profile', 'ND')
                },
                'serotype': {
                    'Serotype': typing.get('Serotype', 'ND'),
                    'O_Type': typing.get('O_Type', 'ND'),
                    'H_Type': typing.get('H_Type', 'ND')
                },
                'chtyper': {
                    'FumC_Type': typing.get('FumC_Type', 'ND'),
                    'FimH_Type': typing.get('FimH_Type', 'ND'),
                    'CH_Type': typing.get('CH_Type', 'ND')
                },
                'phylogrouping': {
                    'Clermont_Type': typing.get('Clermont_Type', 'ND')
                },
                'amr_genes': amr_genes,
                'virulence_genes': virulence_genes,
                'bacmet_genes': bacmet_genes,
                'plasmid_genes': plasmid_genes,
                'pathotype': pathotype
            }

        print("\n🧠 Processing gene-centric analysis...")
        total_samples = len(all_sample_ids)
        integrated['gene_centric'] = self.analyzer.create_gene_centric_tables_from_tsv(integrated, total_samples)
        integrated['patterns'] = self.analyzer.create_cross_genome_patterns(integrated)

        return integrated

    def generate_json_report(self, data: Dict[str, Any]) -> Path:
        print("\n📝 Generating JSON report...")
        out = self.output_dir / "genius_ecoli_ultimate_sample_centric_report.json"
        with open(out, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=2, default=str)
        print(f"    ✅ JSON saved: {out}")
        return out

    def generate_csv_reports(self, data: Dict[str, Any]):
        print("\n📊 Generating CSV reports...")
        samples_df = pd.DataFrame([{
            'Sample': s,
            'ST': d['mlst']['ST'],
            'Serotype': d['serotype']['Serotype'],
            'Phylogroup': d['phylogrouping']['Clermont_Type'],
            'CH_Type': d['chtyper']['CH_Type'],
            'Pathotype': d['pathotype'],
            'AMR_Count': len(d['amr_genes']),
            'Virulence_Count': len(d['virulence_genes'])
        } for s, d in data['samples'].items()])
        samples_df.to_csv(self.output_dir / "sample_overview.csv", index=False)

        print("    ✅ CSV reports generated.")

    def run(self):
        print("=" * 80)
        print("🧠 GENIUS E.COLI ULTIMATE REPORTER v1.0.0")
        print("=" * 80)
        print(f"📁 Input directory: {self.input_dir}")

        html_files = self.find_html_files()
        if not any(html_files.values()):
            print("❌ No HTML report files found!")
            return False

        data = self.integrate_all_data(html_files)
        if not data:
            return False

        print("\n" + "=" * 80)
        print("📊 GENERATING ULTIMATE REPORTS")
        print("=" * 80)
        self.generate_json_report(data)
        self.generate_csv_reports(data)
        self.html_generator.generate_main_report(data, self.output_dir)

        total_samples = len(data['samples'])
        patterns = data['patterns']
        gene_centric = data['gene_centric']
        total_amr = sum(len(genes) for genes in gene_centric.get('amr_databases', {}).values())
        total_vir = sum(len(genes) for genes in gene_centric.get('virulence_databases', {}).values())
        patho_counts = patterns.get('pathotype_distribution', Counter())

        print("\n" + "=" * 80)
        print("✅ ULTIMATE ANALYSIS COMPLETE!")
        print("=" * 80)
        print(f"📁 Output directory: {self.output_dir}")
        print(f"📄 Files generated:")
        print(f"   • genius_ecoli_ultimate_sample_centric_report.html (Interactive hybrid report)")
        print(f"   • genius_ecoli_ultimate_sample_centric_report.json (Complete data)")
        print(f"   • sample_overview.csv (Sample data)")
        print(f"\n📈 ANALYSIS SUMMARY:")
        print(f"   • {total_samples} total samples analyzed")
        print(f"   • {total_amr} AMR genes across all databases (gene‑centric)")
        print(f"   • {total_vir} virulence genes")
        print(f"   • {len(patho_counts)} distinct pathotypes detected")
        print("\n🎯 Next steps:")
        print("   1. Open genius_ecoli_ultimate_sample_centric_report.html in your browser")
        print("   2. Explore the new sample‑centric isolate boxes in AMR, Virulence, Plasmid, Bacmet, Mutations")
        print("   3. Use the filters to search by sample name or database")
        print("   4. Gene‑centric typing tabs remain for epidemiology.")
        print("   5. Export data using the Export tab.")
        print("\n" + "=" * 80)
        return True


def main():
    parser = argparse.ArgumentParser(
        description='GENIUS E.coli Ultimate Reporter v1.0.0',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""Examples:\n  genius_ecoli_ultimate_sample_centric_reporter.py -i /path/to/html/reports\n\nAuthor: Brown Beckley <brownbeckley94@gmail.com>"""
    )
    parser.add_argument('-i', '--input-dir', required=True,
                        help='Directory containing EcoliTyper HTML reports and TSV summaries')
    parser.add_argument('-o', '--output-dir',
                        help='Custom output directory (default: input_dir/GENIUS_ECOLI_ULTIMATE_SAMPLE_CENTRIC_REPORTS)')
