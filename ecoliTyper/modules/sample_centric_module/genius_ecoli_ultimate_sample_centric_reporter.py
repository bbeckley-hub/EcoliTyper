    def load_typing_from_tsv(self, input_dir: Path) -> Dict[str, Dict]:
        """Load typing results from TSV files (MLST, Serotype, CHTyper, Phylogroup)."""
        typing_data = {}
        mlst_path = input_dir / 'mlst_summary.tsv'
        sero_path = input_dir / 'serotype_analysis_report.tsv'
        chtyper_path = input_dir / 'chtyper_results.tsv'
        phylo_path = input_dir / 'phylogrouping_results.tsv'

        if mlst_path.exists():
            df = pd.read_csv(mlst_path, sep='\t')
            for _, row in df.iterrows():
                sample = self.normalize_sample_id(row.get('Sample', row.get('sample', '')))
                if sample:
                    if sample not in typing_data:
                        typing_data[sample] = {}
                    typing_data[sample]['ST'] = self.clean_st(str(row.get('ST', 'ND')))
                    typing_data[sample]['Allele_Profile'] = str(row.get('Allele Profile', 'ND'))

        if sero_path.exists():
            df = pd.read_csv(sero_path, sep='\t')
            for _, row in df.iterrows():
                sample = self.normalize_sample_id(row.get('Sample', row.get('sample', '')))
                if sample:
                    if sample not in typing_data:
                        typing_data[sample] = {}
                    typing_data[sample]['Serotype'] = str(row.get('Serotype', 'ND'))
                    typing_data[sample]['O_Type'] = str(row.get('O-type', row.get('O_Type', 'ND')))
                    typing_data[sample]['H_Type'] = str(row.get('H-type', row.get('H_Type', 'ND')))

        if chtyper_path.exists():
            df = pd.read_csv(chtyper_path, sep='\t')
            for _, row in df.iterrows():
                sample = self.normalize_sample_id(row.get('Sample_ID', row.get('sample', '')))
                if sample:
                    if sample not in typing_data:
                        typing_data[sample] = {}
                    fumc = str(row.get('FumC_Type', 'ND'))
                    fimh = str(row.get('FimH_Type', 'ND'))
                    ch_type = f"{fumc}:{fimh}" if fumc != 'ND' and fimh != 'ND' else 'ND'
                    typing_data[sample]['FumC_Type'] = fumc
                    typing_data[sample]['FimH_Type'] = fimh
                    typing_data[sample]['CH_Type'] = ch_type

        if phylo_path.exists():
            df = pd.read_csv(phylo_path, sep='\t')
            for _, row in df.iterrows():
                sample = self.normalize_sample_id(row.get('Sample', row.get('sample', '')))
                if sample:
                    if sample not in typing_data:
                        typing_data[sample] = {}
                    typing_data[sample]['Clermont_Type'] = str(row.get('Clermont Type', row.get('Type', 'ND')))

        for sample in typing_data:
            for key in ['ST', 'Allele_Profile', 'Serotype', 'O_Type', 'H_Type', 'FumC_Type', 'FimH_Type', 'CH_Type', 'Clermont_Type']:
                if key not in typing_data[sample]:
                    typing_data[sample][key] = 'ND'

        return typing_data

    def load_amrfinder_from_tsv(self, input_dir: Path) -> Tuple[Dict[str, List[Dict]], Dict[str, int]]:
        """Load AMRfinder summary TSV."""
        amr_path = input_dir / 'ecoli_amrfinder_summary.tsv'
        if not amr_path.exists():
            return {}, {}
        df = pd.read_csv(amr_path, sep='\t')
        per_sample = defaultdict(list)
        gene_counts = Counter()
        for _, row in df.iterrows():
            sample = self.normalize_sample_id(row.get('Genome', ''))
            if not sample:
                continue
            gene_dict = row.to_dict()
            gene_dict = {k: (None if pd.isna(v) else v) for k, v in gene_dict.items()}
            if 'Element symbol' in gene_dict:
                gene_dict['gene'] = gene_dict.pop('Element symbol')
            elif 'Element_symbol' in gene_dict:
                gene_dict['gene'] = gene_dict.pop('Element_symbol')
            elif 'Gene' in gene_dict:
                gene_dict['gene'] = gene_dict.pop('Gene')
            if 'gene' not in gene_dict:
                continue
            per_sample[sample].append(gene_dict)
            gene_counts[gene_dict['gene']] += 1
        return dict(per_sample), dict(gene_counts)

    def load_abricate_from_tsv(self, input_dir: Path) -> Tuple[Dict[str, Dict[str, List[Dict]]], Dict[str, Dict[str, int]]]:
        """Load all ABRicate database TSVs."""
        per_sample_db = defaultdict(lambda: defaultdict(list))
        db_gene_counts = defaultdict(lambda: defaultdict(int))

        for db, fname in self.abricate_tsv_files.items():
            path = input_dir / fname
            if not path.exists():
                continue
            df = pd.read_csv(path, sep='\t')
            sample_col = None
            for col in ['genome', 'file']:
                if col in df.columns:
                    sample_col = col
                    break
            if sample_col is None:
                continue
            for _, row in df.iterrows():
                sample = self.normalize_sample_id(row[sample_col])
                if not sample:
                    continue
                gene_dict = row.to_dict()
                gene_dict = {k: (None if pd.isna(v) else v) for k, v in gene_dict.items()}
                if 'gene' not in gene_dict:
                    continue
                per_sample_db[sample][db].append(gene_dict)
                db_gene_counts[db][gene_dict['gene']] += 1

        return dict(per_sample_db), dict(db_gene_counts)

    def load_mutations_from_tsv(self, input_dir: Path) -> Dict[str, List[Dict]]:
        """Load mutation summary TSV."""
        mut_path = input_dir / 'mutation_summary.tsv'
        if not mut_path.exists():
            return {}
        df = pd.read_csv(mut_path, sep='\t')
        per_sample = defaultdict(list)
        for _, row in df.iterrows():
            sample = self.normalize_sample_id(row.get('genome', ''))
            if not sample:
                continue
            def clean_val(v):
                if pd.isna(v):
                    return ''
                return str(v)
            mut_dict = {
                'gene': clean_val(row.get('gene_symbol', row.get('gene', ''))),
                'mutation': clean_val(row.get('element_name', '')),
                'class': clean_val(row.get('class', '')),
                'subclass': clean_val(row.get('subclass', '')),
                'contig': clean_val(row.get('contig_id', '')),
                'start': clean_val(row.get('start', '')),
                'stop': clean_val(row.get('stop', '')),
                'strand': clean_val(row.get('strand', '')),
                'coverage': clean_val(row.get('coverage', '')),
                'identity': clean_val(row.get('identity', '')),
                'accession': clean_val(row.get('accession', ''))
            }
            per_sample[sample].append(mut_dict)
        return dict(per_sample)


