    def classify_pathotype(self, virulence_genes: List[str]) -> str:
        genes = set(gene.lower() for gene in virulence_genes)
        stx = any(g in genes for g in ['stx1', 'stx2', 'stx1a', 'stx1b', 'stx2a', 'stx2b'])
        eae = 'eae' in genes
        bfp = 'bfpa' in genes
        agg = any(g in genes for g in ['aggr', 'aaiac', 'aata', 'aaiC', 'aatA'])
        lt = 'ltca' in genes
        st = 'sta1' in genes
        afa = any(g in genes for g in ['afac', 'afae'])
        ipa = 'ipah' in genes
        pathotypes = []
        if stx and not eae:
            pathotypes.append('STEC')
        if (eae or bfp) and not stx:
            pathotypes.append('EPEC')
        if stx and eae:
            pathotypes.append('EHEC')
        if agg:
            pathotypes.append('EAEC')
        if lt or st:
            pathotypes.append('ETEC')
        if afa:
            pathotypes.append('DAEC')
        if ipa:
            pathotypes.append('EIEC')
        if not pathotypes:
            return 'none'
        return '-'.join(pathotypes)

    def create_gene_centric_tables_from_tsv(self, integrated_data: Dict[str, Any], total_samples: int) -> Dict[str, Any]:
        """Build gene-centric tables from TSV data (per-sample gene lists)."""
        gene_centric = {
            'amr_databases': {},
            'virulence_databases': {},
            'bacmet_databases': {},
            'plasmid_databases': {},
            'combined_gene_frequencies': [],
            'database_stats': {}
        }

        samples_data = integrated_data.get('samples', {})

        amr_gene_counts = Counter()
        virulence_gene_counts = Counter()
        bacmet_gene_counts = Counter()
        plasmid_gene_counts = Counter()
        amr_genomes = defaultdict(list)
        virulence_genomes = defaultdict(list)
        bacmet_genomes = defaultdict(list)
        plasmid_genomes = defaultdict(list)

        for sample, data in samples_data.items():
            for gene in data.get('amr_genes', []):
                amr_gene_counts[gene] += 1
                if sample not in amr_genomes[gene]:
                    amr_genomes[gene].append(sample)
            for gene in data.get('virulence_genes', []):
                virulence_gene_counts[gene] += 1
                if sample not in virulence_genomes[gene]:
                    virulence_genomes[gene].append(sample)
            for gene in data.get('bacmet_genes', []):
                bacmet_gene_counts[gene] += 1
                if sample not in bacmet_genomes[gene]:
                    bacmet_genomes[gene].append(sample)
            for gene in data.get('plasmid_genes', []):
                plasmid_gene_counts[gene] += 1
                if sample not in plasmid_genomes[gene]:
                    plasmid_genomes[gene].append(sample)

        if amr_gene_counts:
            gene_list = []
            for gene, count in amr_gene_counts.most_common():
                genome_list = amr_genomes.get(gene, [])
                percentage = (count / total_samples) * 100 if total_samples > 0 else 0
                gene_list.append({
                    'gene': gene,
                    'database': 'AMRfinder',
                    'count': count,
                    'percentage': round(percentage, 2),
                    'frequency_display': f"{count} ({percentage:.1f}%)",
                    'genomes': genome_list
                })
            if gene_list:
                gene_centric['amr_databases']['amrfinder'] = gene_list

        if virulence_gene_counts:
            gene_list = []
            for gene, count in virulence_gene_counts.most_common():
                genome_list = virulence_genomes.get(gene, [])
                percentage = (count / total_samples) * 100 if total_samples > 0 else 0
                gene_list.append({
                    'gene': gene,
                    'database': 'VFDB',
                    'count': count,
                    'percentage': round(percentage, 2),
                    'frequency_display': f"{count} ({percentage:.1f}%)",
                    'genomes': genome_list
                })
            if gene_list:
                gene_centric['virulence_databases']['vfdb'] = gene_list

        if bacmet_gene_counts:
            gene_list = []
            for gene, count in bacmet_gene_counts.most_common():
                genome_list = bacmet_genomes.get(gene, [])
                percentage = (count / total_samples) * 100 if total_samples > 0 else 0
                gene_list.append({
                    'gene': gene,
                    'database': 'BACMET2',
                    'count': count,
                    'percentage': round(percentage, 2),
                    'frequency_display': f"{count} ({percentage:.1f}%)",
                    'genomes': genome_list
                })
            if gene_list:
                gene_centric['bacmet_databases']['bacmet2'] = gene_list

        if plasmid_gene_counts:
            gene_list = []
            for gene, count in plasmid_gene_counts.most_common():
                genome_list = plasmid_genomes.get(gene, [])
                percentage = (count / total_samples) * 100 if total_samples > 0 else 0
                gene_list.append({
                    'gene': gene,
                    'database': 'PLASMIDFINDER',
                    'count': count,
                    'percentage': round(percentage, 2),
                    'frequency_display': f"{count} ({percentage:.1f}%)",
                    'genomes': genome_list
                })
            if gene_list:
                gene_centric['plasmid_databases']['plasmidfinder'] = gene_list

        all_genes = []
        for db_type in ['amr_databases', 'virulence_databases', 'bacmet_databases', 'plasmid_databases']:
            for db_name, genes in gene_centric.get(db_type, {}).items():
                all_genes.extend(genes)
        all_genes.sort(key=lambda x: x['count'], reverse=True)
        gene_centric['combined_gene_frequencies'] = all_genes

        for db_type in ['amr_databases', 'virulence_databases', 'bacmet_databases', 'plasmid_databases']:
            for db_name, genes in gene_centric.get(db_type, {}).items():
                gene_centric['database_stats'][db_name] = {
                    'total_genes': len(genes),
                    'total_occurrences': sum(g['count'] for g in genes),
                }

        return gene_centric

    def create_cross_genome_patterns(self, integrated_data: Dict[str, Any]) -> Dict[str, Any]:
        patterns = {
            'st_distribution': Counter(),
            'serotype_distribution': Counter(),
            'phylogroup_distribution': Counter(),
            'ch_type_distribution': Counter(),
            'o_type_distribution': Counter(),
            'h_type_distribution': Counter(),
            'fumc_type_distribution': Counter(),
            'fimh_type_distribution': Counter(),
            'pathotype_distribution': Counter(),
            'st_o_combinations': defaultdict(list),
            'st_h_combinations': defaultdict(list),
            'st_oh_combinations': defaultdict(list),
            'st_phylogroup_combinations': defaultdict(list),
            'st_fimh_combinations': defaultdict(list),
            'st_fumc_combinations': defaultdict(list),
            'st_fumc_fimh_combinations': defaultdict(list),
            'st_oh_phylo_fumc_fimh_combinations': defaultdict(list),
            'gene_cooccurrence': defaultdict(Counter),
            'high_risk_combinations': []
        }
        samples_data = integrated_data.get('samples', {})
        sample_genes = defaultdict(list)

        for sample, data in samples_data.items():
            for gene in data.get('amr_genes', []):
                if gene not in sample_genes[sample]:
                    sample_genes[sample].append(gene)
            for gene in data.get('virulence_genes', []):
                if gene not in sample_genes[sample]:
                    sample_genes[sample].append(gene)

        for sample, data in samples_data.items():
            st = data.get('mlst', {}).get('ST', 'ND')
            serotype = data.get('serotype', {}).get('Serotype', 'ND')
            o_type = data.get('serotype', {}).get('O_Type', 'ND')
            h_type = data.get('serotype', {}).get('H_Type', 'ND')
            phylogroup = data.get('phylogrouping', {}).get('Clermont_Type', 'ND')
            fumc = data.get('chtyper', {}).get('FumC_Type', 'ND')
            fimh = data.get('chtyper', {}).get('FimH_Type', 'ND')
            ch_type = data.get('chtyper', {}).get('CH_Type', 'ND')
            pathotype = data.get('pathotype', 'none')

            if st != 'ND':
                patterns['st_distribution'][st] += 1
            if serotype != 'ND':
                patterns['serotype_distribution'][serotype] += 1
            if o_type != 'ND':
                patterns['o_type_distribution'][o_type] += 1
            if h_type != 'ND':
                patterns['h_type_distribution'][h_type] += 1
            if phylogroup != 'ND':
                patterns['phylogroup_distribution'][phylogroup] += 1
            if ch_type != 'ND':
                patterns['ch_type_distribution'][ch_type] += 1
            if fumc != 'ND':
                patterns['fumc_type_distribution'][fumc] += 1
            if fimh != 'ND':
                patterns['fimh_type_distribution'][fimh] += 1
            patterns['pathotype_distribution'][pathotype] += 1

            if st != 'ND' and o_type != 'ND':
                patterns['st_o_combinations'][f"{st} - {o_type}"].append(sample)
            if st != 'ND' and h_type != 'ND':
                patterns['st_h_combinations'][f"{st} - {h_type}"].append(sample)
            if st != 'ND' and serotype != 'ND':
                patterns['st_oh_combinations'][f"{st} - {serotype}"].append(sample)
            if st != 'ND' and phylogroup != 'ND':
                patterns['st_phylogroup_combinations'][f"{st} - {phylogroup}"].append(sample)
            if st != 'ND' and fimh != 'ND':
                patterns['st_fimh_combinations'][f"{st} - {fimh}"].append(sample)
            if st != 'ND' and fumc != 'ND':
                patterns['st_fumc_combinations'][f"{st} - {fumc}"].append(sample)
            if st != 'ND' and ch_type != 'ND':
                patterns['st_fumc_fimh_combinations'][f"{st} - {ch_type}"].append(sample)
            if st != 'ND' and serotype != 'ND' and phylogroup != 'ND' and ch_type != 'ND':
                full_combo = f"{st} - {serotype} - {phylogroup} - {ch_type}"
                patterns['st_oh_phylo_fumc_fimh_combinations'][full_combo].append(sample)

            genes = sample_genes.get(sample, [])
            for i, g1 in enumerate(genes):
                for g2 in genes[i+1:]:
                    patterns['gene_cooccurrence'][g1][g2] += 1

            amr_genes = data.get('amr_genes', [])
            virulence_genes = data.get('virulence_genes', [])
            critical_amr = [g for g in amr_genes if any(crit.lower() in g.lower() for crit in self.critical_amr_genes)]
            critical_vir = [g for g in virulence_genes if any(crit.lower() in g.lower() for crit in self.critical_virulence_genes)]
            if critical_amr and critical_vir:
                patterns['high_risk_combinations'].append({
                    'sample': sample,
                    'st': st,
                    'serotype': serotype,
                    'critical_amr_genes': critical_amr,
                    'critical_virulence_genes': critical_vir
                })

        return patterns


